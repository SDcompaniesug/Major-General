CREATE TABLE IF NOT EXISTS member_mutes (
  group_jid TEXT NOT NULL REFERENCES groups(jid) ON DELETE CASCADE,
  user_jid TEXT NOT NULL,
  muted_until TIMESTAMPTZ NOT NULL,
  moderator_jid TEXT NOT NULL,
  PRIMARY KEY(group_jid,user_jid)
);
CREATE TABLE IF NOT EXISTS group_messages (
  id BIGSERIAL PRIMARY KEY,
  group_jid TEXT NOT NULL REFERENCES groups(jid) ON DELETE CASCADE,
  user_jid TEXT NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS group_messages_recent_idx ON group_messages(group_jid,created_at DESC);
CREATE TABLE IF NOT EXISTS group_bad_words (
  group_jid TEXT NOT NULL REFERENCES groups(jid) ON DELETE CASCADE,
  word TEXT NOT NULL,
  PRIMARY KEY(group_jid,word)
);

CREATE TABLE IF NOT EXISTS bot_settings (
  key TEXT PRIMARY KEY,
  value JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
